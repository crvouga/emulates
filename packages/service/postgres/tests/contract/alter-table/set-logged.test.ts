// CREATE UNLOGGED TABLE, ALTER TABLE ... SET LOGGED | UNLOGGED and pg_class.relpersistence (issue #333).
// The engine has no write-ahead log: the three persistence modes differ only in what the catalog
// reports and in which statements PostgreSQL accepts.
//
// The oracle session is shared across tests and its reset keeps pg_temp, so every temporary
// object here has a name of its own (tmp_sl_*) and is dropped by the test that created it.

/**
 * relpersistence of the named relations. Key constraints have no pg_class index row of their own
 * in every build of the engine, so probes name the relations they compare instead of listing all.
 */
const persistenceOf = (...names: string[]): string =>
  "SELECT c.relname, c.relkind, c.relpersistence FROM pg_class c " +
  `WHERE c.relname IN (${names.map((n) => `'${n}'`).join(", ")}) ORDER BY c.relname`;

