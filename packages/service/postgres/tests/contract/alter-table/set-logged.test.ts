matrixBoth("persistence survives a snapshot reload", async (memory, postgres) => {
  try {
    await setupBoth(memory, postgres, [
      "CREATE TABLE logged_kv (id integer PRIMARY KEY, value text)",
      "CREATE UNLOGGED TABLE unlogged_kv (id serial, value text, parent_id integer REFERENCES logged_kv (id))",
      "CREATE INDEX unlogged_kv_value ON unlogged_kv (value)",
      "CREATE TABLE converted_kv (id serial, value text)",
      "ALTER TABLE converted_kv SET UNLOGGED",
      "CREATE TEMP TABLE tmp_sl_reload (id integer)",
      "CREATE UNLOGGED SEQUENCE unlogged_seq",
      "INSERT INTO logged_kv VALUES (1, 'a')",
      "INSERT INTO unlogged_kv (value, parent_id) VALUES ('u', 1)",
      "CREATE UNLOGGED TABLE selected AS SELECT * FROM unlogged_kv",
    ]);
    memory.restore(memory.snapshot());
    expectParity(await memory.query(RELOAD_RELATIONS), await postgres.query(RELOAD_RELATIONS));
    // the reloaded metadata still drives the conversion rules
    for (const sql of [
      "ALTER TABLE logged_kv SET UNLOGGED",
      "ALTER TABLE unlogged_kv SET LOGGED",
      "ALTER TABLE converted_kv SET LOGGED",
      "CREATE TABLE refused (parent_id integer REFERENCES logged_kv (id))",
    ]) {
      expectParity(await memory.exec(sql), await postgres.exec(sql), { ignoreWriteCounters: true });
    }
    memory.restore(memory.snapshot());
    expectParity(await memory.query(RELOAD_RELATIONS), await postgres.query(RELOAD_RELATIONS));
    const rows = "SELECT id, value, parent_id FROM unlogged_kv";
    expectParity(await memory.query(rows), await postgres.query(rows));
  } finally {
    await postgres.exec("DROP TABLE IF EXISTS tmp_sl_reload");
  }
});

test("a snapshot without unlogged relations carries no persistence metadata", () => {
  const converted = new Database();
  const plain = new Database();
  try {
    for (const db of [converted, plain]) db.exec("CREATE TABLE kv (id serial, value text)");
    converted.exec("ALTER TABLE kv SET UNLOGGED");
    converted.exec("ALTER TABLE kv SET LOGGED");
    // Back to logged is byte-identical to never having been unlogged, which is also
    // what a snapshot written before relpersistence was modelled looks like.
    expect(converted.snapshot().encode()).toEqual(plain.snapshot().encode());
    const reopened = plain.snapshot().open();
    expect(reopened.query("SELECT relpersistence FROM pg_class WHERE relname = 'kv'")).toEqual([
      { relpersistence: "p" },
    ]);
    reopened.close();
  } finally {
    converted.close();
    plain.close();
  }
});
