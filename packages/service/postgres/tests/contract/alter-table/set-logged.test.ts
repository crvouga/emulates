for (const target of ["UNLOGGED", "LOGGED"] as const) {
  for (const [name, sql] of VIOLATIONS) {
    errorParity(
      `after SET ${target} the table still enforces ${name}`,
      [
        "CREATE TABLE owners (id integer PRIMARY KEY)",
        "INSERT INTO owners VALUES (1)",
        `CREATE TABLE kv (
           id integer PRIMARY KEY, value text NOT NULL, amount integer CHECK (amount > 0),
           owner integer REFERENCES owners (id)
         )`,
        "CREATE UNIQUE INDEX kv_amount_uq ON kv (amount)",
        "INSERT INTO kv VALUES (1, 'a', 1, 1), (2, 'b', 2, 1)",
        "ALTER TABLE kv SET UNLOGGED",
        ...(target === "LOGGED" ? ["ALTER TABLE kv SET LOGGED"] : []),
      ],
      sql,
      undefined,
      { messageTier: "A" },
    );
  }
}

